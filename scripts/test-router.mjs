import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
// Import browser ES modules without requiring a package.json in this static site.
const source = await readFile(new URL('../static/router.js', import.meta.url), 'utf8');
const { createRouter } = await import(`data:text/javascript;base64,${Buffer.from(source).toString('base64')}`);
const tree = JSON.parse(await readFile(new URL('../static/tree.json', import.meta.url)));
let destination;
const options = { root: 'https://example.com/blog/', navigate: url => { destination = url; } };
const root = createRouter(tree, options);
root.commands('cd tell/poems'); assert.equal(destination, 'https://example.com/blog/tell/poems/');
assert.deepEqual(root.commands('cd code'), ['fatal: coming soon']);
assert.deepEqual(root.complete('cd co'), []);
const datedPoem = root.commands('find Joie de la découverte')[0];
assert.equal(datedPoem.href, 'https://example.com/blog/tell/poems/joie-de-la-decouverte/');
assert.deepEqual(root.complete('cd tell/po'), ['cd tell/poems/']);
const poems = createRouter(tree, { ...options, directory: '/tell/poems/' });
poems.commands('cat euphonie'); assert.match(destination, /2025-euphonie\/$/);
poems.commands('cd ..'); assert.equal(destination, 'https://example.com/blog/tell/');
poems.commands('cd ~'); assert.equal(destination, 'https://example.com/blog/');
assert.ok(poems.commands('find découverte').some(row => row.text === 'Joie de la découverte'));
assert.match(poems.commands('stat')[0], /^225 pages/);
assert.equal(poems.commands('head').length, 10);
assert.equal(poems.commands('tail').length, 10);
poems.commands('random'); assert.match(destination, /\/tell\/poems\/[^/]+\/$/);
root.commands('cd ..'); assert.equal(destination, 'https://g-ongenae.github.io/');
assert.match(root.commands('cat tell')[0], /Is a directory/);
assert.match(root.commands('cd nowhere')[0], /no such file/);
assert.equal(root.commands('ls -la').length, 8);
assert.ok(root.commands('tree').length > 8);
console.log('Router checks passed.');
